/**
 * Re-copies the two standalone rental portals into the superapp.
 *
 * apps/admin-portal and apps/owner-portal remain the editable source of truth
 * and the deployment rollback path. apps/web/src/modules/rental holds derived
 * copies of both. Edit a portal, run this, push once — otherwise the superapp
 * silently keeps serving the old screens.
 *
 * Everything under apps/web/src/modules/rental/{admin,owner} is REGENERATED.
 * Never hand-edit those trees; change the portal and re-run.
 *
 * Usage: node scripts/sync-rental.mjs [--check]
 *   --check  report drift and exit non-zero without writing (for CI)
 */
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('../', import.meta.url))
const CHECK = process.argv.includes('--check')

const TREES = [
  {
    name: 'admin',
    from: 'apps/admin-portal/src',
    to: 'apps/web/src/modules/rental/admin',
    alias: '@rental-admin',
    // Entry points and sign-in belong to the superapp, not the module.
    drop: ['main.tsx', 'index.css', 'vite-env.d.ts', 'routes/login-page.tsx'],
  },
  {
    name: 'owner',
    from: 'apps/owner-portal/src',
    to: 'apps/web/src/modules/rental/owner',
    alias: '@rental-owner',
    drop: ['main.tsx', 'index.css', 'vite-env.d.ts', 'App.tsx', 'routes/login.tsx'],
  },
]

const PREFIX = '/app/rental'

/** The superapp owns one client and one cache; two of either breaks auth/invalidation. */
const SINGLETONS = {
  'lib/supabase.ts': `/**
 * Repointed at the superapp singleton. Two clients would mean two auth
 * sessions racing each other's token refresh.
 *
 * GENERATED by scripts/sync-rental.mjs — do not edit.
 */
export { supabase } from '@/lib/supabase'
`,
  'lib/query-client.ts': `/**
 * Repointed at the superapp singleton. A second QueryClient would mean
 * mutations invalidating a cache nobody reads from.
 *
 * GENERATED by scripts/sync-rental.mjs — do not edit.
 */
export { queryClient } from '@/lib/query-client'
`,
}

/**
 * Route tables are rewritten rather than patched: mounted behind the
 * /app/rental/* splat every `path` must be RELATIVE, and neither tree carries
 * a login screen any more.
 */
const ROUTE_FILES = {
  admin: {
    path: 'routes/index.tsx',
    // Derived from the portal's own route table; keep in step when routes change.
    contents: null, // filled in below
  },
  owner: { path: 'routes/index.tsx', contents: null },
}

function walk(dir, base = dir) {
  const out = []
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry)
    if (statSync(full).isDirectory()) out.push(...walk(full, base))
    else out.push(relative(base, full))
  }
  return out
}

/**
 * Rewrites a portal file for life inside the superapp:
 *  - `@/` becomes the module's own alias so it never collides with the superapp
 *  - absolute in-app links gain the /app/rental prefix, because navItemForPath,
 *    canAccessRoute and homeRouteForRole all match against real pathnames
 *  - /login is handed back to the superapp
 */
function transform(source, alias) {
  let s = source
  s = s.replaceAll("'@/", `'${alias}/`).replaceAll('"@/', `"${alias}/`)
  s = s
    .replaceAll('to="/', `to="${PREFIX}/`)
    .replaceAll('to={`/', `to={\`${PREFIX}/`)
    .replaceAll("navigate('/", `navigate('${PREFIX}/`)
    .replaceAll('navigate(`/', `navigate(\`${PREFIX}/`)
    .replaceAll("to: '/", `to: '${PREFIX}/`)
  s = s.replaceAll(`${PREFIX}/login`, '/login')
  return s
}

