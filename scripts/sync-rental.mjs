// ── Build each tree in memory, then compare or write ─────────────────────────
let drift = 0

for (const tree of TREES) {
  const fromDir = join(ROOT, tree.from)
  if (!existsSync(fromDir)) {
    console.error(`missing source: ${tree.from}`)
    process.exit(1)
  }

  const built = new Map()
  for (const rel of walk(fromDir)) {
    if (tree.drop.includes(rel.split('\\').join('/'))) continue
    const full = join(fromDir, rel)
    if (/\.(ts|tsx)$/.test(rel)) built.set(rel, transform(readFileSync(full, 'utf8'), tree.alias))
    else built.set(rel, readFileSync(full))
  }
  for (const [rel, contents] of Object.entries(SINGLETONS)) built.set(rel, contents)
  built.set(ROUTE_FILES[tree.name].path, ROUTE_FILES[tree.name].contents)

  const toDir = join(ROOT, tree.to)

  if (CHECK) {
    const existing = existsSync(toDir) ? new Set(walk(toDir)) : new Set()
    for (const [rel, contents] of built) {
      const target = join(toDir, rel)
      const current = existsSync(target) ? readFileSync(target) : null
      const want = Buffer.isBuffer(contents) ? contents : Buffer.from(contents)
      if (current === null || !current.equals(want)) {
        console.log(`  drift: ${tree.to}/${rel}`)
        drift++
      }
      existing.delete(rel)
    }
    for (const rel of existing) {
      console.log(`  stale: ${tree.to}/${rel}`)
      drift++
    }
    continue
  }

  rmSync(toDir, { recursive: true, force: true })
  for (const [rel, contents] of built) {
    const target = join(toDir, rel)
    mkdirSync(join(target, '..'), { recursive: true })
    writeFileSync(target, contents)
  }
  console.log(`  ${tree.to}: ${built.size} files`)
}

if (CHECK) {
  if (drift) {
    console.error(`\n${drift} file(s) out of sync. Run: node scripts/sync-rental.mjs`)
    process.exit(1)
  }
  console.log('rental module is in sync')
} else {
  console.log('\nSynced. Now run: pnpm typecheck')
}
